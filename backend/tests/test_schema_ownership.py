"""Tests for the schema ownership of the application.

The schema is owned by the Alembic migrations, not by the application: the app
never creates a table, it only verifies at startup that the schema matches the
migrations. These tests pin that contract:

* the migrated schema matches the ORM (the migration chain cannot drift away
  from ``backend/app/models.py`` without the suite failing);
* the application refuses to start against a database that was not migrated,
  and says what to run;
* the migrations repair a database that an older version of the application
  created, instead of accepting a schema the application cannot use;
* a rollback never drops a table that still holds rows.
"""

import asyncio
import os
import sqlite3
import subprocess
import sys

import pytest
from fastapi.testclient import TestClient
from sqlalchemy.engine import make_url
from sqlalchemy.ext.asyncio import create_async_engine

from backend.app.database import Base
from backend.app.main import app
import backend.app.main as main_module


REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BACKEND_DIR = os.path.join(REPO_ROOT, "backend")
DATABASE_PATH = make_url(os.environ["DATABASE_URL"]).database


def _tables_in(database_path):
    """The tables of a SQLite database."""
    connection = sqlite3.connect(database_path)
    try:
        return {
            row[0]
            for row in connection.execute(
                "SELECT name FROM sqlite_master WHERE type='table'"
            )
        }
    finally:
        connection.close()


def _alembic(*arguments, database_url):
    """Run an Alembic command against ``database_url`` and return the result."""
    environment = dict(os.environ, DATABASE_URL=database_url)
    return subprocess.run(
        [sys.executable, "-m", "alembic", *arguments],
        cwd=BACKEND_DIR,
        env=environment,
        capture_output=True,
        text=True,
    )


def test_the_migrated_schema_matches_the_orm():
    """The tables the ORM declares are exactly the tables the migrations create.

    The test database is built by ``alembic upgrade head`` (see the session
    fixture in ``conftest.py``), so a drift between the migration chain and
    ``backend/app/models.py`` fails here instead of being papered over by the
    application.
    """
    migrated = _tables_in(DATABASE_PATH)
    declared = {table.name for table in Base.metadata.sorted_tables}

    assert declared <= migrated, (
        f"the migrations did not create the table(s) {sorted(declared - migrated)}"
    )
    # The vestigial "notes" table of the previous project must be gone.
    assert "notes" not in migrated


def test_the_schema_has_no_drift_against_the_orm():
    """The migrated schema and the ORM must agree in every detail.

    ``alembic check`` compares the migrated database with the metadata of the
    ORM and reports every difference it finds: a column that only the ORM
    knows, a column only the migration knows, a table that exists in one of
    them and not in the other. Comparing the table names alone would miss
    most of those, and the drift would then surface as an obscure error in an
    unrelated test - or not at all.
    """
    from alembic import command
    from alembic.config import Config
    from alembic.util.exc import AutogenerateDiffsDetected

    config = Config(os.path.join(BACKEND_DIR, "alembic.ini"))
    config.set_main_option("script_location", os.path.join(BACKEND_DIR, "migrations"))

    try:
        command.check(config)
    except AutogenerateDiffsDetected as exc:
        pytest.fail(
            f"the migrated schema and the ORM disagree: {exc}. Add a migration "
            f"for the difference, or align the model with the migration."
        )


def test_the_startup_check_fails_with_an_actionable_message(tmp_path, monkeypatch):
    """An unmigrated database is a deployment error, not a runtime condition.

    The application must say what to run instead of failing with an opaque
    "no such table" further down.
    """
    empty_db = tmp_path / "empty.db"
    sqlite3.connect(empty_db).close()

    engine = create_async_engine(f"sqlite+aiosqlite:///{empty_db}")
    monkeypatch.setattr(main_module, "engine", engine)

    with pytest.raises(RuntimeError) as excinfo:
        asyncio.run(main_module.verify_schema())

    message = str(excinfo.value)
    assert "alembic upgrade head" in message
    assert "training_runs" in message

    asyncio.run(engine.dispose())


def test_a_never_migrated_database_is_refused(tmp_path, monkeypatch):
    """A database the application created itself is not a migrated database.

    It has the right tables but no migration history, so the next
    ``alembic upgrade head`` would try to create the tables again. The
    application must not start against it.
    """
    legacy_db = tmp_path / "legacy.db"

    async def create_with_the_orm():
        engine = create_async_engine(f"sqlite+aiosqlite:///{legacy_db}")
        async with engine.begin() as connection:
            await connection.run_sync(Base.metadata.create_all)
        await engine.dispose()

    asyncio.run(create_with_the_orm())
    assert "alembic_version" not in _tables_in(legacy_db)

    engine = create_async_engine(f"sqlite+aiosqlite:///{legacy_db}")
    monkeypatch.setattr(main_module, "engine", engine)

    with pytest.raises(RuntimeError) as excinfo:
        asyncio.run(main_module.verify_schema())

    message = str(excinfo.value)
    assert "alembic_version" in message
    assert "alembic upgrade head" in message

    asyncio.run(engine.dispose())


def test_a_column_drift_is_refused(tmp_path, monkeypatch):
    """A table with the right name but the wrong columns is not usable.

    This is the shape of a database that an older version of the application
    created: the application would fail on the first query that touches a
    missing column, so the startup check has to catch it.
    """
    drifted_db = tmp_path / "drifted.db"
    connection = sqlite3.connect(drifted_db)
    connection.executescript(
        """
        CREATE TABLE users (
            id INTEGER NOT NULL PRIMARY KEY,
            username VARCHAR UNIQUE,
            hashed_password VARCHAR,
            role VARCHAR
        );
        CREATE TABLE training_runs (
            id INTEGER NOT NULL PRIMARY KEY,
            owner_id INTEGER NOT NULL,
            model_name VARCHAR NOT NULL,
            dataset_source VARCHAR NOT NULL,
            dataset_tag VARCHAR NOT NULL,
            hyperparameters JSON NOT NULL,
            metrics JSON,
            artifact_path VARCHAR
        );
        CREATE TABLE alembic_version (version_num VARCHAR(32) NOT NULL);
        """
    )
    connection.commit()
    connection.close()

    engine = create_async_engine(f"sqlite+aiosqlite:///{drifted_db}")
    monkeypatch.setattr(main_module, "engine", engine)

    with pytest.raises(RuntimeError) as excinfo:
        asyncio.run(main_module.verify_schema())

    message = str(excinfo.value)
    assert "status" in message
    assert "alembic upgrade head" in message

    asyncio.run(engine.dispose())


def test_the_migration_repairs_a_drifted_database(tmp_path):
    """``alembic upgrade head`` fixes a database with the wrong columns.

    A database that an older version of the application created has the right
    table name but not the current columns. The migration adds the missing
    ones instead of stamping the revision and leaving the schema broken.
    """
    drifted_db = tmp_path / "drifted.db"
    connection = sqlite3.connect(drifted_db)
    connection.executescript(
        """
        CREATE TABLE users (
            id INTEGER NOT NULL PRIMARY KEY,
            username VARCHAR UNIQUE,
            hashed_password VARCHAR,
            role VARCHAR
        );
        CREATE TABLE training_runs (
            id INTEGER NOT NULL PRIMARY KEY,
            owner_id INTEGER NOT NULL,
            model_name VARCHAR NOT NULL,
            dataset_source VARCHAR NOT NULL,
            dataset_tag VARCHAR NOT NULL,
            hyperparameters JSON NOT NULL,
            metrics JSON,
            artifact_path VARCHAR
        );
        """
    )
    connection.commit()
    connection.close()

    result = _alembic(
        "upgrade", "head", database_url=f"sqlite+aiosqlite:///{drifted_db}"
    )
    assert result.returncode == 0, result.stderr

    connection = sqlite3.connect(drifted_db)
    columns = {
        row[1] for row in connection.execute("PRAGMA table_info(training_runs)")
    }
    connection.close()

    assert {"status", "optimize_metric", "mode", "created_at"} <= columns, (
        f"the migration did not add the missing columns: {sorted(columns)}"
    )


def test_the_downgrade_does_not_destroy_data(tmp_path):
    """A rollback must never drop a table that still holds rows.

    The chain may run on a database that the application created itself, so a
    table it finds can hold data that it did not create. Dropping it during a
    rollback would destroy that data, so the downgrade refuses.
    """
    legacy_db = tmp_path / "legacy.db"
    connection = sqlite3.connect(legacy_db)
    connection.executescript(
        """
        CREATE TABLE users (
            id INTEGER NOT NULL PRIMARY KEY,
            username VARCHAR UNIQUE,
            hashed_password VARCHAR,
            role VARCHAR
        );
        INSERT INTO users (username, hashed_password, role)
            VALUES ('carol', 'hash', 'user');
        """
    )
    connection.commit()
    connection.close()

    upgrade = _alembic("upgrade", "head", database_url=f"sqlite+aiosqlite:///{legacy_db}")
    assert upgrade.returncode == 0, upgrade.stderr

    downgrade = _alembic(
        "downgrade", "base", database_url=f"sqlite+aiosqlite:///{legacy_db}"
    )
    assert downgrade.returncode != 0, "the downgrade dropped a table with data"

    connection = sqlite3.connect(legacy_db)
    rows = list(connection.execute("SELECT username FROM users"))
    connection.close()
    assert rows == [("carol",)], "the downgrade destroyed the rows of the users table"


def test_the_migrations_can_render_their_sql_without_a_database(tmp_path):
    """``alembic upgrade head --sql`` must work.

    The offline mode cannot inspect the live database, so the migrations fall
    back to the schema of a fresh installation. This is the mode a reviewer
    uses to read the DDL before it is applied.
    """
    result = _alembic(
        "upgrade",
        "head",
        "--sql",
        database_url=f"sqlite+aiosqlite:///{tmp_path / 'unused.db'}",
    )
    assert result.returncode == 0, result.stderr
    assert "CREATE TABLE training_runs" in result.stdout


def test_the_application_uses_a_lifespan_handler_instead_of_on_event():
    """The deprecated startup hook must not come back.

    ``@app.on_event("startup")`` warns on every import and on every test run.
    A lifespan handler leaves the router's ``on_startup`` list empty.
    """
    assert app.router.on_startup == [], (
        "a startup event handler is registered: the deprecated on_event hook "
        "must not be used, the lifespan handler is the replacement"
    )


def test_the_app_refuses_to_start_against_an_unmigrated_database(
    tmp_path, monkeypatch
):
    """The check runs in the lifespan, so the application does not start.

    This is the contract the deployment relies on: a database that is not
    migrated is a startup error, not a runtime surprise.
    """
    empty_db = tmp_path / "empty.db"
    sqlite3.connect(empty_db).close()

    engine = create_async_engine(f"sqlite+aiosqlite:///{empty_db}")
    monkeypatch.setattr(main_module, "engine", engine)

    with pytest.raises(RuntimeError, match="alembic upgrade head"):
        with TestClient(app):
            pass

    asyncio.run(engine.dispose())


def test_the_app_starts_against_the_migrated_database():
    """The lifespan runs the schema check and lets a migrated database through."""
    with TestClient(app) as client:
        response = client.get("/api/v1/ml/models")
        assert response.status_code == 200
